const dictionaries: Record<Language, Dict> = { fr, en };

/**
 * Traduit une clé avec interpolation optionnelle : t('x.y', { count: 3 })
 * remplace "{count}" dans la chaîne. Retombe sur le français puis sur la clé.
 */
export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  let str = dictionaries[language][key] ?? dictionaries.fr[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value));
    }
  }
  return str;
}

/** Locale BCP-47 pour toLocaleDateString / toLocaleTimeString. */
export function dateLocale(language: Language): string {
  return language === 'en' ? 'en-CA' : 'fr-CA';
}

/** Ajoute des clés de traduction (réservé aux dictionnaires par écran si besoin). */
export function getDictionary(language: Language): Dict {
  return dictionaries[language];
}
